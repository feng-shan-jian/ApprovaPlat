DROP TABLE IF EXISTS wf_collaboration_outbox;

CREATE TABLE wf_collaboration_outbox
(
    message_id VARCHAR(36) NOT NULL PRIMARY KEY,
    channel_id VARCHAR(64) NOT NULL,
    sequence_no BIGINT NOT NULL,
    source_process_definition_key VARCHAR(255) NOT NULL,
    source_process_instance_id VARCHAR(64) NOT NULL,
    source_execution_id VARCHAR(64) NOT NULL,
    source_element_id VARCHAR(255) NOT NULL,
    message_name VARCHAR(255) NOT NULL,
    target_process_definition_key VARCHAR(255) NOT NULL,
    correlation_key VARCHAR(255) NOT NULL,
    endpoint_id BIGINT NOT NULL,
    endpoint_revision INT NOT NULL,
    request_path VARCHAR(512) NOT NULL,
    delivery_config_json VARCHAR(4096) NOT NULL,
    variables_json VARCHAR(4096) NOT NULL,
    payload_sha256 VARCHAR(64) NOT NULL,
    status VARCHAR(16) NOT NULL,
    attempt_count INT NOT NULL DEFAULT 0,
    max_attempts INT NOT NULL DEFAULT 5,
    compensation_count INT NOT NULL DEFAULT 0,
    revision_no INT NOT NULL DEFAULT 0,
    lease_owner VARCHAR(64),
    lease_until TIMESTAMP(3),
    next_attempt_time TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    last_http_status INT,
    last_error_code VARCHAR(64),
    last_error_summary VARCHAR(512),
    create_time TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    last_attempt_time TIMESTAMP(3),
    complete_time TIMESTAMP(3)
);
