-- H2 的 IN 常量集合会捕获建表连接；用等价 CASE 约束保留跨事务校验。
CREATE TABLE IF NOT EXISTS `wf_copy`
(
    `copy_id`         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    `copy_event_id`   VARCHAR(128) NOT NULL,
    `title`           VARCHAR(255) NOT NULL DEFAULT '',
    `process_id`      VARCHAR(64)  NOT NULL,
    `process_name`    VARCHAR(255) NOT NULL DEFAULT '',
    `category_id`     VARCHAR(64)  NOT NULL DEFAULT '',
    `deployment_id`   VARCHAR(64)  NOT NULL,
    `instance_id`     VARCHAR(64)  NOT NULL,
    `task_id`         VARCHAR(64)           DEFAULT NULL,
    `user_id`         BIGINT       NOT NULL,
    `originator_id`   BIGINT       NOT NULL,
    `originator_name` VARCHAR(64)  NOT NULL DEFAULT '',
    `source_type`     VARCHAR(16)  NOT NULL DEFAULT 'MANUAL',
    `trigger_type`    VARCHAR(32)  NOT NULL DEFAULT 'MANUAL_COMPLETE',
    `trigger_node_id` VARCHAR(64)           DEFAULT NULL,
    `trigger_node_name` VARCHAR(255)        DEFAULT NULL,
    `read_status`     CHAR(1)      NOT NULL DEFAULT '0',
    `read_time`       TIMESTAMP(3)           DEFAULT NULL,
    `create_by`       VARCHAR(64)  NOT NULL DEFAULT '',
    `create_time`     TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `update_by`       VARCHAR(64)  NOT NULL DEFAULT '',
    `update_time`     TIMESTAMP              DEFAULT NULL,
    `remark`          VARCHAR(255)          DEFAULT NULL,
    `del_flag`        CHAR(1)      NOT NULL DEFAULT '0',
    PRIMARY KEY (`copy_id`),
    CONSTRAINT `uk_wf_copy_event_user` UNIQUE (`copy_event_id`, `user_id`),
    CONSTRAINT `chk_wf_copy_del_flag` CHECK (CASE
        WHEN `del_flag` = '0' THEN TRUE
        WHEN `del_flag` = '2' THEN TRUE
        ELSE FALSE END),
    CONSTRAINT `chk_wf_copy_source_type` CHECK (CASE
        WHEN `source_type` = 'MANUAL' THEN TRUE
        WHEN `source_type` = 'AUTO' THEN TRUE
        WHEN `source_type` = 'MANUAL_AUTO' THEN TRUE
        ELSE FALSE END),
    CONSTRAINT `chk_wf_copy_trigger_type` CHECK (CASE
        WHEN `trigger_type` = 'MANUAL_COMPLETE' THEN TRUE
        WHEN `trigger_type` = 'MANUAL_REJECT' THEN TRUE
        WHEN `trigger_type` = 'MANUAL_RETURN' THEN TRUE
        WHEN `trigger_type` = 'MANUAL_DELEGATE' THEN TRUE
        WHEN `trigger_type` = 'MANUAL_RESOLVE' THEN TRUE
        WHEN `trigger_type` = 'MANUAL_TRANSFER' THEN TRUE
        WHEN `trigger_type` = 'NODE_ARRIVED' THEN TRUE
        WHEN `trigger_type` = 'NODE_COMPLETED' THEN TRUE
        WHEN `trigger_type` = 'PROCESS_COMPLETED' THEN TRUE
        ELSE FALSE END),
    CONSTRAINT `chk_wf_copy_read_state` CHECK ((`read_status` = '0' AND `read_time` IS NULL)
        OR (`read_status` = '1' AND `read_time` IS NOT NULL))
);
