create table wf_bpmn_extension (
    extension_id bigint generated by default as identity primary key,
    extension_key varchar(128) not null unique,
    extension_name varchar(128) not null,
    extension_type varchar(32) not null,
    status varchar(16) not null,
    description varchar(500), create_by varchar(64) not null,
    create_time timestamp default current_timestamp, update_by varchar(64), update_time timestamp
);
create table wf_bpmn_extension_version (
    version_id bigint generated by default as identity primary key,
    extension_id bigint not null references wf_bpmn_extension(extension_id),
    version_no int not null, implementation_key varchar(128) not null,
    config_schema clob not null, checksum varchar(64) not null,
    create_by varchar(64) not null, create_time timestamp default current_timestamp,
    unique(extension_id, version_no)
);
