CREATE TABLE wf_collaboration_channel (
    channel_id VARCHAR(64) PRIMARY KEY,
    delivery_mode VARCHAR(16) NOT NULL DEFAULT 'COLLABORATION',
    target_process_definition_key VARCHAR(255) NOT NULL,
    correlation_type VARCHAR(32) NOT NULL,
    correlation_value VARCHAR(255) NOT NULL,
    outbound_sequence BIGINT NOT NULL DEFAULT 0,
    inbound_sequence BIGINT NOT NULL DEFAULT 0,
    revision_no INT NOT NULL DEFAULT 0,
    update_time TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP(3),
    UNIQUE(delivery_mode,target_process_definition_key,correlation_type,correlation_value)
);
CREATE TABLE wf_collaboration_message_audit (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id VARCHAR(36) NOT NULL,
    direction VARCHAR(16) NOT NULL,
    action VARCHAR(32) NOT NULL,
    actor_type VARCHAR(16) NOT NULL,
    actor_id VARCHAR(64) NOT NULL,
    from_status VARCHAR(16),
    to_status VARCHAR(16) NOT NULL,
    attempt_no INT NOT NULL,
    error_code VARCHAR(64),
    summary VARCHAR(512) NOT NULL,
    create_time TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP(3)
);
